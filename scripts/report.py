#!/usr/bin/env python3
"""Renders results/raw/*.jsonl into docs/results.md.

Each benchmark script appends one JSON object per run. Runs with the same
label are repeats (interleaved rounds); tables show the median and, where it
matters, the min-max range across repeats.

    python3 scripts/report.py [--raw results/raw] [--out docs/results.md]
"""
import argparse
import json
import os
import statistics
from collections import OrderedDict


def load(path):
    runs = OrderedDict()
    if not os.path.exists(path):
        return runs
    with open(path) as f:
        for line in f:
            line = line.strip()
            if line:
                r = json.loads(line)
                runs.setdefault(r.get("label", ""), []).append(r)
    return runs


def med(rs, key):
    vals = [r[key] for r in rs if key in r]
    return statistics.median(vals) if vals else float("nan")


def rng(rs, key, fmt):
    vals = [r[key] for r in rs if key in r]
    if len(vals) < 2:
        return ""
    return f" ({fmt.format(min(vals))}–{fmt.format(max(vals))})"


def k(n):
    if n >= 1e6:
        return f"{n / 1e6:.2f}M"
    if n >= 1e3:
        return f"{n / 1e3:.1f}K"
    return f"{n:.0f}"


def ms(us):
    return f"{us / 1000:.2f} ms" if us >= 1000 else f"{us:.0f} µs"


def engine_table(runs):
    out = ["| Configuration | Durable writes/s | p50 | p99 | Runs |", "|---|---|---|---|---|"]
    for label, rs in runs.items():
        out.append(
            f"| `{label}` | {k(med(rs, 'writes_per_s'))}{rng(rs, 'writes_per_s', '{:,.0f}')} "
            f"| {ms(med(rs, 'w_p50_us'))} | {ms(med(rs, 'w_p99_us'))} | {len(rs)} |")
    return out


def load_table(runs, reads=True):
    hdr = "| Configuration | Writes/s | Write p50 | Write p99 | Write p99.9 |"
    sep = "|---|---|---|---|---|"
    if reads:
        hdr += " Reads/s | Read p99 |"
        sep += "---|---|"
    out = [hdr + " Runs |", sep + "---|"]
    for label, rs in runs.items():
        batched = any(r.get("batch", 1) > 1 for r in rs)
        wps = k(med(rs, "keys_per_s")) + f" keys ({rs[0]['batch']}/RPC)" if batched else k(med(rs, "writes_per_s"))
        row = (f"| `{label}` | {wps} | {ms(med(rs, 'w_p50_us'))} "
               f"| {ms(med(rs, 'w_p99_us'))}{rng(rs, 'w_p99_us', '{:,.0f}')} | {ms(med(rs, 'w_p999_us'))} |")
        if reads:
            rps = med(rs, "reads_per_s")
            row += (f" {k(rps)} | {ms(med(rs, 'r_p99_us'))} |" if rps and rps > 0 else " – | – |")
        out.append(row + f" {len(rs)} |")
    return out


def recovery_table(runs):
    out = ["| Scenario | Keys recovered | Restart → ready | Snapshot load | WAL replay | Missing | Runs |",
           "|---|---|---|---|---|---|---|"]
    for label, rs in runs.items():
        out.append(
            f"| `{label}` | {k(med(rs, 'keys'))} | **{med(rs, 'open_s'):.3f} s**{rng(rs, 'open_s', '{:.3f}')} "
            f"| {med(rs, 'snapshot_s'):.3f} s | {med(rs, 'wal_s'):.3f} s | {int(max(r['missing'] for r in rs))} | {len(rs)} |")
    return out


def chaos_table(runs):
    out = ["| Run | Kills (graceful) | Acked writes | Lost | Stale reads | Failover p50 / p90 / max | Graceful handover p50 |",
           "|---|---|---|---|---|---|---|"]
    for label, rs in runs.items():
        for r in rs:
            out.append(
                f"| `{label}` | {r['kills']} ({r['graceful']}) | {r['writes']:,} | **{r['lost']}** | **{r['stale_reads']}** "
                f"| {r['failover_p50_ms']:.0f} / {r['failover_p90_ms']:.0f} / {r['failover_max_ms']:.0f} ms "
                f"| {r['handover_p50_ms']:.0f} ms |")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default="results/raw")
    ap.add_argument("--out", default="docs/results.md")
    ap.add_argument("--title", default="Results")
    ap.add_argument("--preamble", default="", help="extra paragraph after the title")
    a = ap.parse_args()
    host = {}
    hp = os.path.join(a.raw, "host.json")
    if os.path.exists(hp):
        host = json.load(open(hp))

    doc = [f"# {a.title}", "",
           f"Generated by `scripts/report.py` from the JSON lines in `{a.raw}/`. "
           "Every number below comes from a script in `scripts/` and can be reproduced with it.", ""]
    if a.preamble:
        doc += [a.preamble, ""]
    if host:
        doc += ["## Host", ""]
        for key, val in host.items():
            if val:
                doc.append(f"- **{key}**: {val}")
        doc.append("")
    if "shared" in str(host.get("note", "")):
      doc += ["## Reading these numbers", "",
            "Every write below is acknowledged only after `fdatasync`, so most numbers scale with the "
            "device's flush latency. These runs shared the machine with other services that also flush the "
            "same NVMe, and the raw 4 KiB overwrite+fdatasync latency during the runs was ~1.5 ms, about six "
            "times what the drive does when idle. Treat the absolute throughput and latency as conservative. "
            "The comparisons (global lock vs pipelined, this engine vs RocksDB) were interleaved round by "
            "round, so both sides saw the same conditions. Recovery and failover are not flush-bound and "
            "barely move. Ranges show min–max across rounds.", ""]
    else:
      doc += ["Ranges show min–max across interleaved rounds.", ""]
    sections = [
        ("engine.jsonl", "Storage engine (in-process, `scripts/bench-engine.sh`)", engine_table,
         "16 client threads, 100-byte values, every write fdatasync-durable before it is acknowledged "
         "unless the label says `nosync`. `d1` = each thread blocks on its write; `d64`/`d256` = each "
         "thread keeps that many async writes in flight. `global` is the naive design (one mutex held "
         "across append, fdatasync and apply). RocksDB 8.9 runs with `WriteOptions::sync=true` on the same disk."),
        ("contention.jsonl", "Lock contention at 32 clients (gRPC, `scripts/bench-contention.sh`)",
         lambda r: load_table(r, True),
         "Standalone `kvd`, 32 closed-loop gRPC clients with one request in flight each. Configurations "
         "are interleaved round by round so drift in the shared disk's flush latency affects both. "
         "Ranges are across rounds."),
        ("cluster.jsonl", "Replicated cluster (3 nodes, `scripts/bench-cluster.sh`)",
         lambda r: load_table(r, True),
         "Three `kvd` processes on one host, each with its own WAL on the same NVMe; a write is "
         "acknowledged after the leader and at least one follower have fsynced it and it is applied. "
         "`sess` adds exactly-once session tracking; `linear` reads use ReadIndex, `lease` reads use the leader lease."),
        ("recovery.jsonl", "Crash recovery (`scripts/bench-recovery.sh`)", recovery_table,
         "A child process loads the keys (100-byte values), optionally checkpoints, writes the WAL tail, "
         "and is killed with SIGKILL. The parent times `Engine::Open` and then reads every key back. "
         "`cold` evicts all data files from the page cache first."),
        ("chaos.jsonl", "Failure testing (`scripts/bench-chaos.sh`)", chaos_table,
         "16 writers against a 3-node cluster; the leader is SIGKILLed every 3 s and restarted 1 s later "
         "(every 4th cycle SIGTERM instead, which hands leadership over first). Failover = kill to the "
         "first write acknowledged by another node. Lost = keys whose final value is below the last "
         "acknowledged write; stale = linearizable reads that returned a value older than an acknowledged write."),
    ]
    for fname, title, fn, note in sections:
        runs = load(os.path.join(a.raw, fname))
        if not runs:
            continue
        doc += [f"## {title}", "", note, ""] + fn(runs) + [""]
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as f:
        f.write("\n".join(doc))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
